-- 1. INNER JOIN: Combine Product details with Category name and Available Stock
SELECT 
    p.product_id,
    p.product_name,
    c.category_name,
    p.unit_price,
    i.available_stock,
    (p.unit_price * i.available_stock) AS total_inventory_valuation
FROM products p
JOIN categories c ON p.category_id = c.category_id
JOIN inventory i ON p.product_id = i.product_id
ORDER BY p.product_id;

-- 2. Multi-table JOIN: Itemized Sales Details with Customer, Product, and Category info
SELECT 
    st.transaction_id,
    st.transaction_date,
    cust.customer_name,
    p.product_name,
    c.category_name,
    sd.quantity_sold,
    sd.unit_price,
    sd.subtotal,
    st.payment_mode
FROM sales_transactions st
JOIN customers cust ON st.customer_id = cust.customer_id
JOIN sales_details sd ON st.transaction_id = sd.transaction_id
JOIN products p ON sd.product_id = p.product_id
JOIN categories c ON p.category_id = c.category_id
ORDER BY st.transaction_id ASC, sd.detail_id ASC;

-- 3. Aggregation with GROUP BY: Total Quantity and Revenue generated by each Product
SELECT 
    p.product_id,
    p.product_name,
    SUM(sd.quantity_sold) AS total_units_sold,
    ROUND(SUM(sd.subtotal), 2) AS total_revenue
FROM products p
JOIN sales_details sd ON p.product_id = sd.product_id
GROUP BY p.product_id, p.product_name
ORDER BY total_revenue DESC;

-- 4. Aggregation with HAVING: Categories generating more than $100 in revenue
SELECT 
    c.category_name,
    COUNT(DISTINCT sd.transaction_id) AS transactions_count,
    SUM(sd.quantity_sold) AS total_items_sold,
    ROUND(SUM(sd.subtotal), 2) AS category_revenue
FROM categories c
JOIN products p ON c.category_id = p.category_id
JOIN sales_details sd ON p.product_id = sd.product_id
GROUP BY c.category_id, c.category_name
HAVING category_revenue > 100.00
ORDER BY category_revenue DESC;

-- 5. Payment Mode Turnover Analysis
SELECT 
    payment_mode,
    COUNT(transaction_id) AS total_transactions,
    ROUND(SUM(total_amount), 2) AS total_turnover,
    ROUND(AVG(total_amount), 2) AS avg_transaction_amount
FROM sales_transactions
GROUP BY payment_mode
ORDER BY total_turnover DESC;
